/**
 * Writes wrangler.jsonc for your deployment. Without --local it also creates
 * the D1 database, R2 bucket and KV namespace in your Cloudflare account (or
 * reuses them if they exist) and applies the database migrations.
 *
 *   npm run setup -- --local
 *   npm run setup -- --domain home.example.com --owner you@example.com
 *
 * Options (prompted for when missing, except with --local):
 *   --domain     host the app is served on; must be a zone in your Cloudflare account
 *   --owner      email address of the first member
 *   --from       sender for sign-in codes and reminders, e.g. "Home Inventory <inventory@example.com>"
 *   --ingest     address people forward receipts to, e.g. inventory@example.com
 *   --timezone   IANA zone for warranty dates (default: this machine's)
 *   --currency   ISO 4217 code (default USD)
 *   --name       app name shown in the UI (default "Home Inventory")
 *   --worker     Worker and resource name prefix (default home-inventory-mcp)
 *   --no-ai      leave out the Workers AI binding (no text extraction from PDFs and images)
 *
 * Re-running is safe: existing resources are found by name and reused.
 */
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { parseArgs } from "node:util";

const { values: args } = parseArgs({
  options: {
    local: { type: "boolean", default: false },
    domain: { type: "string" },
    owner: { type: "string" },
    from: { type: "string" },
    ingest: { type: "string" },
    timezone: { type: "string" },
    currency: { type: "string", default: "USD" },
    name: { type: "string", default: "Home Inventory" },
    worker: { type: "string", default: "home-inventory-mcp" },
    "no-ai": { type: "boolean", default: false }
  }
});

const CONFIG = "wrangler.jsonc";
const COMPATIBILITY_DATE = "2026-08-22";

const wrangler = (...cmd: string[]): string => execFileSync("npx", ["wrangler", ...cmd], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

const ask = async (question: string, fallback?: string): Promise<string> => {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const answer = (await rl.question(fallback ? `${question} [${fallback}]: ` : `${question}: `)).trim();
  rl.close();
  return answer || fallback || ask(question, fallback);
};

interface Settings {
  worker: string;
  domain: string | null;
  publicUrl: string;
  owner: string;
  from: string | null;
  ingest: string | null;
  timezone: string;
  currency: string;
  name: string;
  d1Id: string;
  kvId: string;
  ai: boolean;
  local: boolean;
}

const render = (s: Settings): string => {
  const vars: Record<string, string> = {
    APP_NAME: s.name,
    PUBLIC_URL: s.publicUrl,
    OWNER_EMAIL: s.owner,
    TIMEZONE: s.timezone,
    CURRENCY: s.currency
  };
  if (s.from) vars.EMAIL_FROM = s.from;
  if (s.ingest) vars.INGEST_ADDRESS = s.ingest;
  if (s.local) vars.DEV_LOG_CODES = "1";

  const config: Record<string, unknown> = {
    $schema: "node_modules/wrangler/config-schema.json",
    name: s.worker,
    main: "worker/index.ts",
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat"],
    workers_dev: false,
    preview_urls: false,
    ...(s.domain ? { routes: [{ pattern: s.domain, custom_domain: true }] } : {}),
    assets: { binding: "ASSETS", not_found_handling: "single-page-application", run_worker_first: true },
    d1_databases: [{ binding: "DB", database_name: s.worker, database_id: s.d1Id, migrations_dir: "migrations" }],
    r2_buckets: [{ binding: "FILES", bucket_name: `${s.worker}-files` }],
    kv_namespaces: [{ binding: "OAUTH_KV", id: s.kvId }],
    ...(s.local ? {} : { send_email: [{ name: "EMAIL" }] }),
    ...(s.ai && !s.local ? { ai: { binding: "AI" } } : {}),
    triggers: { crons: ["0 13 * * *"] },
    vars,
    observability: { enabled: true }
  };
  return `// Generated by \`npm run setup\`${s.local ? " --local (local development only)" : ""}. Safe to edit; re-running setup overwrites it.\n${JSON.stringify(config, null, 2)}\n`;
};

const findD1 = (name: string): string | undefined =>
  (JSON.parse(wrangler("d1", "list", "--json")) as { uuid: string; name: string }[]).find((d) => d.name === name)?.uuid;

const findKv = (title: string): string | undefined =>
  (JSON.parse(wrangler("kv", "namespace", "list")) as { id: string; title: string }[]).find((n) => n.title === title)?.id;

const ensureResources = (worker: string): { d1Id: string; kvId: string } => {
  let d1Id = findD1(worker);
  if (!d1Id) {
    console.log(`Creating D1 database ${worker}…`);
    wrangler("d1", "create", worker);
    d1Id = findD1(worker);
  }
  if (!d1Id) throw new Error(`Couldn't find the D1 database ${worker} after creating it.`);

  const kvTitle = `${worker}-oauth`;
  let kvId = findKv(kvTitle);
  if (!kvId) {
    console.log(`Creating KV namespace ${kvTitle}…`);
    wrangler("kv", "namespace", "create", kvTitle);
    kvId = findKv(kvTitle);
  }
  if (!kvId) throw new Error(`Couldn't find the KV namespace ${kvTitle} after creating it.`);

  const bucket = `${worker}-files`;
  try {
    console.log(`Creating R2 bucket ${bucket}…`);
    wrangler("r2", "bucket", "create", bucket);
  } catch (e) {
    const out = String((e as { stderr?: string }).stderr ?? e);
    if (!/already exists|already owned/i.test(out)) throw e;
  }
  return { d1Id, kvId };
};

const main = async () => {
  const worker = args.worker!;
  const timezone = args.timezone ?? Intl.DateTimeFormat().resolvedOptions().timeZone ?? "UTC";

  if (args.local) {
    writeFileSync(
      CONFIG,
      render({
        worker,
        domain: null,
        publicUrl: "http://localhost:5173",
        owner: args.owner ?? "you@example.com",
        from: null,
        ingest: args.ingest ?? null,
        timezone,
        currency: args.currency!,
        name: args.name!,
        d1Id: "00000000-0000-0000-0000-000000000000",
        kvId: "local",
        ai: false,
        local: true
      })
    );
    wrangler("d1", "migrations", "apply", "DB", "--local");
    console.log(`Wrote ${CONFIG} for local development and migrated the local database.`);
    console.log(`Run \`npm run dev\` and sign in as ${args.owner ?? "you@example.com"}. Sign-in codes are printed in the terminal.`);
    return;
  }

  try {
    wrangler("whoami");
  } catch {
    throw new Error("Wrangler isn't signed in. Run `npx wrangler login` first.");
  }
  if (existsSync(CONFIG)) console.log(`${CONFIG} exists and will be overwritten.`);

  const domain = args.domain ?? (await ask("Domain to serve the app on (a host in a zone on your Cloudflare account)"));
  const owner = (args.owner ?? (await ask("Your email address (the first member)"))).toLowerCase();
  const apex = domain.split(".").slice(-2).join(".");
  const from = args.from ?? (await ask("From address for sign-in codes", `${args.name} <inventory@${apex}>`));
  const ingest = args.ingest ?? (await ask("Address to forward receipts to", `inventory@${apex}`));

  const { d1Id, kvId } = ensureResources(worker);
  writeFileSync(
    CONFIG,
    render({
      worker,
      domain,
      publicUrl: `https://${domain}`,
      owner,
      from,
      ingest,
      timezone,
      currency: args.currency!,
      name: args.name!,
      d1Id,
      kvId,
      ai: !args["no-ai"],
      local: false
    })
  );
  console.log(`Wrote ${CONFIG}. Applying migrations…`);
  execFileSync("npx", ["wrangler", "d1", "migrations", "apply", "DB", "--remote"], { stdio: "inherit" });

  const sender = /<([^>]+)>/.exec(from)?.[1] ?? from;
  console.log(`
Done. Next:
  1. Enable Email Sending for ${sender.split("@")[1]} (Cloudflare dashboard → Email Service, or \`npx wrangler email sending enable ${sender.split("@")[1]}\`).
  2. Deploy: npm run deploy
  3. Route ${ingest} to the Worker: Email Routing → Routing rules → Send to a Worker → ${worker}.
  4. Open https://${domain} and sign in as ${owner} with an email code.`);
};

main().catch((e: unknown) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
